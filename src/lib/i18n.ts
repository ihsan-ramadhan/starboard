const DICT: Record<Lang, Record<TKey, string>> = { id, en };

function read(): Lang {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (raw === "id" || raw === "en") return raw;
  } catch {}
  return "id";
}

let current: Lang = read();
document.documentElement.lang = current;
const listeners = new Set<() => void>();

export function getLang(): Lang {
  return current;
}

export function setLang(next: Lang) {
  if (next === current) return;
  current = next;
  try {
    localStorage.setItem(STORAGE_KEY, next);
  } catch {}
  document.documentElement.lang = next;
  for (const notify of listeners) notify();
}

function subscribe(notify: () => void) {
  listeners.add(notify);
  return () => {
    listeners.delete(notify);
  };
}

export type TVars = Record<string, string | number>;

export function translate(lang: Lang, key: TKey, vars?: TVars): string {
  const text = DICT[lang][key];
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (whole, name: string) =>
    name in vars ? String(vars[name]) : whole
  );
}

export function t(key: TKey, vars?: TVars): string {
  return translate(current, key, vars);
}

export function dateLocale(): string {
  return current === "en" ? "en-GB" : "id-ID";
}

export function numberLocale(): string {
  return current === "en" ? "en-GB" : "id-ID";
}

export type Translate = (key: TKey, vars?: TVars) => string;

export function useLang(): Lang {
  return useSyncExternalStore(subscribe, getLang, getLang);
}

export function useT() {
  const lang = useLang();
  return useCallback(
    (key: TKey, vars?: TVars) => translate(lang, key, vars),
    [lang]
  );
}
